"""Regenerate the README status block from evals/results/*.json.

Every number in the README status table is read from a results file here, so
the README cannot drift from what the eval harness measured.
    python -m evals.status
"""
from __future__ import annotations

import json
from pathlib import Path

R = Path("evals/results")
BEGIN, END = "<!-- STATUS:BEGIN (generated by python -m evals.status; do not edit by hand) -->", "<!-- STATUS:END -->"


def _load(name):
    p = R / name
    return json.loads(p.read_text()) if p.exists() else None


def block() -> str:
    L = []
    p1, p2, rob = _load("part1.json"), _load("part2.json"), _load("robustness.json")
    L += ["### Part 1 -- beat grid and sync ([evals/results/part1.md](evals/results/part1.md))", ""]
    if p1:
        tp = [r for r in p1["clips"] if not r.get("generated") and not r.get("substitute") and not str(r["id"]).startswith("user:")]
        subs = [r for r in p1["clips"] if r.get("substitute")]
        gen = [r for r in p1["clips"] if r.get("generated")]
        missing = [r["id"] for r in tp if r["status"] != "ok"]
        L.append(f"- **Test pack:** {'not present at eval time (' + ', '.join(missing) + ' missing) -- nothing measured on it' if missing else 'measured'}.")
        L += ["", "| clip | kind | beat F | downbeat F | max drift ms | mean signed ms | BPM | type | meter |", "|---|---|---|---|---|---|---|---|---|"]
        for r in [x for x in tp if x["status"] == "ok"] + subs + gen:
            d = r.get("drift") if isinstance(r.get("drift"), dict) else {}
            kind = "SUBSTITUTE (GTZAN)" if r.get("substitute") else "generated" if r.get("generated") else "test pack"
            L.append(f"| {r['id']} | {kind} | {r.get('beat_f')} | {r.get('downbeat_f')} | {d.get('max_abs_ms', '-')} | "
                     f"{d.get('mean_signed_ms', '-')} | {r.get('bpm')} | {r.get('tempo_type')} | {r.get('meter')} |")
        for s in p1["sync"]:
            if s["status"] == "ok":
                k = s["kick_alignment"]
                L.append(f"- Sync {s['pair']} ({'generated' if s.get('generated') else 'test pack'}): kick offsets median "
                         f"{k.get('median_abs_offset_ms')} ms, max {k.get('max_abs_offset_ms')} ms over {k.get('n_pairs')} pairs.")
            else:
                L.append(f"- Sync {s['pair']}: **{s['status']}**.")
        sixmin = next((r for r in gen if "6min" in r["id"]), None)
        if sixmin:
            L.append(f"- Speed: {sixmin['duration_s']} s generated track analysed in {sixmin['runtime_s']} s on this laptop CPU.")
    else:
        L.append("- not run")
    L += ["", "### Generalisation / robustness on generated audio ([evals/results/robustness.md](evals/results/robustness.md))", ""]
    if rob:
        c = {k: sum(1 for r in rob if r["status"] == k) for k in ("pass", "partial", "fail")}
        L.append(f"- {c['pass']} pass, {c['partial']} partial, {c['fail']} fail of {len(rob)} cases.")
        for r in rob:
            if r["status"] != "pass":
                L.append(f"  - {r['status']}: `{r['name']}` -- {'; '.join(n.splitlines()[0] for n in r['notes'])}")
    L += ["", "### Part 2 -- chat editing ([evals/results/part2.md](evals/results/part2.md))", ""]
    if p2 and "sessions" in p2:
        L.append(f"- Model `{p2['model']}`, real API (cached for re-runs). Cumulative LLM spend so far: "
                 f"{p2['cumulative']['calls']} calls, est. ${p2['cumulative']['est_cost_usd']:.4f} (upper-bound pricing).")
        L += ["", "| session | ran on | statuses | clicks at splices | hard-cut control flagged | grid vs re-tracked (beat F) |",
              "|---|---|---|---|---|---|"]
        for s in p2["sessions"]:
            if s.get("status") == "missing":
                L.append(f"| {s['id']} | **missing** | - | - | - | - |")
                continue
            sp = [x for t in s["turns"] for x in t.get("splices", [])]
            hc = [x for t in s["turns"] for x in t.get("splices_hard_cut_control", [])]
            gc = [t["grid_check"].get("beat_f_at_grid_level", t["grid_check"].get("beat_f_vs_redetected"))
                  for t in s["turns"] if t.get("grid_check")]
            L.append(f"| {s['id']} | {s['clip']} ({s['clip_kind']}) | {', '.join(t['status'] for t in s['turns'])} | "
                     f"{sum(x['flagged'] for x in sp)} / {len(sp)} | {sum(x['flagged'] for x in hc)} / {len(hc)} | "
                     f"{', '.join(map(str, gc)) or '-'} |")
    else:
        L.append(f"- not run{(': ' + p2['error']) if p2 and 'error' in p2 else ''}")
    p3 = _load("part3.json")
    L += ["", "### Part 3 -- audio to Web Audio ([evals/results/part3.md](evals/results/part3.md))", ""]
    if p3:
        L += ["| clip | kind | stands in for | drum onsets F | drums by class F | pitched F | render onset F | page safety |",
              "|---|---|---|---|---|---|---|---|"]
        for r in p3["clips"]:
            if r.get("status") != "ok":
                L.append(f"| {r['id']} | {r['kind']} | {r.get('stands_in_for', '-')} | **{r.get('status')}** | | | | |")
                continue
            n = r.get("notes") or {}
            g = lambda k: (n.get(k) or {}).get("f", "-") if n else "no reference"
            L.append(f"| {r['id']} | {r['kind']} | {r.get('stands_in_for', '-')} | {g('drum_onsets_any_class')} | "
                     f"{g('drums_by_class')} | {g('pitched')} | {r['onset_timing'].get('onset_f_50ms', '-')} | "
                     f"{'ok' if not r['safety_violations'] else 'VIOLATION'} |")
        ch = p3.get("chat") or {}
        if ch.get("turns"):
            L.append(f"- Chat on the recreation of {ch['clip']}: " + "; ".join(f"\"{t['user']}\" -> {t['status']}" for t in ch["turns"]))
    else:
        L.append("- not run")
    return "\n".join(L)


def main():
    readme = Path("README.md")
    text = readme.read_text(encoding="utf-8")
    a, b = text.index(BEGIN), text.index(END)
    readme.write_text(text[:a + len(BEGIN)] + "\n" + block() + "\n" + text[b:], encoding="utf-8")
    print("README status block regenerated")


if __name__ == "__main__":
    main()
